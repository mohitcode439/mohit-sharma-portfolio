-- Portfolio content. Read-only for the application: rows are managed through migrations.

create table profile (
    id            bigint primary key,
    full_name     varchar(100)  not null,
    headline      varchar(200)  not null,
    tagline       varchar(300)  not null,
    current_position varchar(200) not null,
    location      varchar(100)  not null,
    email         varchar(254)  not null,
    avatar_url    varchar(500),
    about         varchar(4000) not null -- paragraphs separated by a blank line
);

create table social_link (
    id         bigint primary key,
    label      varchar(50)  not null,
    url        varchar(500) not null,
    sort_order int          not null
);

create table experience (
    id         bigint primary key,
    company    varchar(150) not null,
    title      varchar(150) not null,
    location   varchar(100) not null,
    start_date date         not null,
    end_date   date, -- null while the role is current
    sort_order int          not null
);

create table experience_highlight (
    experience_id bigint        not null references experience (id),
    sort_order    int           not null,
    content       varchar(1000) not null,
    primary key (experience_id, sort_order)
);

create table skill_category (
    id         bigint primary key,
    name       varchar(100) not null,
    sort_order int          not null
);

create table skill (
    category_id bigint       not null references skill_category (id),
    sort_order  int          not null,
    name        varchar(100) not null,
    primary key (category_id, sort_order)
);

create table project (
    id          bigint primary key,
    name        varchar(150)  not null,
    description varchar(2000) not null,
    image_url   varchar(500),
    live_url    varchar(500),
    github_url  varchar(500),
    sort_order  int           not null
);

create table project_tech (
    project_id bigint       not null references project (id),
    sort_order int          not null,
    name       varchar(100) not null,
    primary key (project_id, sort_order)
);

create table education (
    id          bigint primary key,
    institution varchar(200) not null,
    degree      varchar(200) not null,
    minor       varchar(200),
    start_year  int          not null,
    end_year    int          not null,
    cgpa        varchar(20),
    sort_order  int          not null
);

create table achievement (
    id         bigint primary key,
    content    varchar(500) not null,
    sort_order int          not null
);

-- Messages from the contact form. Kept even when the email notification fails.
create table contact_message (
    id         bigint generated by default as identity primary key,
    name       varchar(100)             not null,
    email      varchar(254)             not null,
    message    varchar(5000)            not null,
    created_at timestamp with time zone not null,
    email_sent boolean                  not null
);
